/** One wash: a shape filled with pigment, roughened by one of the three filters. */
const wash = (d, fill, opacity = 0.6, f = "w2") =>
  `<path d="${d}" fill="${fill}" opacity="${opacity}" filter="url(#${f})"/>`;

/** One pen line, sometimes broken, drawn a second time faintly beside itself like a quick hand. */
function pen(rand, d, width = 1.6, { opacity = 0.9, broken = false, twice = true, color = P.ink } = {}) {
  const dash = broken ? ` stroke-dasharray="${Math.round(40 + rand() * 80)} ${Math.round(4 + rand() * 7)}"` : "";
  const main = `<path d="${d}" fill="none" stroke="${color}" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round" opacity="${opacity}"${dash}/>`;
  if (!twice) return main;
  const dx = f1((rand() - 0.5) * 1.6);
  const dy = f1((rand() - 0.5) * 1.6);
  return `${main}<path d="${d}" transform="translate(${dx} ${dy})" fill="none" stroke="${color}" stroke-width="${f1(width * 0.5)}" stroke-linecap="round" opacity="${f1(opacity * 0.35)}"/>`;
}

/* The tracks: a centre line (a cubic Bézier) and a gauge that shrinks with the distance. Seen from a low height, the offset between
   the rails is mostly vertical, so a sleeper leans like in a drawing in perspective. */
function railOffset(b, gauge) {
  let nx = -b.ty;
  let ny = b.tx;
  if (ny < 0) {
    nx = -nx;
    ny = -ny;
  }
  return [nx * 0.3 * (gauge / 2), ny * 0.42 * (gauge / 2)];
}

function track(rand, curve, g0, g1, { from = 0, to = 1, sleepers = true } = {}) {
  const N = 90;
  const left = [];
  const right = [];
  const ties = [];
  let acc = 0;
  let prev;
  for (let i = 0; i <= N; i++) {
    const t = from + ((to - from) * i) / N;
    const b = bezier(curve, t);
    const g = g0 + (g1 - g0) * t;
    const [ox, oy] = railOffset(b, g);
    left.push([b.x - ox, b.y - oy]);
    right.push([b.x + ox, b.y + oy]);
    if (prev) acc += Math.hypot(b.x - prev.x, b.y - prev.y);
    prev = b;
    if (sleepers && acc > g * 0.5) {
      acc = 0;
      ties.push({ a: [b.x - ox * 1.4 - g * 0.06, b.y - oy * 1.4], z: [b.x + ox * 1.4 + g * 0.06, b.y + oy * 1.4], g });
    }
  }
  const ballast = left.map(([x, y], i) => [x - (right[i][0] - x) * 0.9, y - (right[i][1] - y) * 0.9]);
  const ballastR = right.map(([x, y], i) => [x + (x - left[i][0]) * 0.9, y + (y - left[i][1]) * 0.9]).reverse();
  const out = [wash(polyD([...ballast, ...ballastR]), P.stone, 0.5, "w3")];
  for (const s of ties) {
    out.push(
      `<path d="${lineD([s.a, s.z])}" stroke="${P.wood}" stroke-width="${f1(s.g * 0.17)}" stroke-linecap="butt" opacity="0.6" filter="url(#w3)"/>`,
    );
    if (rand() < 0.5) out.push(pen(rand, lineD([s.a, s.z]), 0.7, { opacity: 0.3, twice: false }));
  }
  out.push(pen(rand, lineD(left), 1.5, { opacity: 0.85 }));
  out.push(pen(rand, lineD(right), 2.1, { opacity: 0.9 }));
  return out.join("\n");
}

