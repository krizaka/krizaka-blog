/** Telegraph poles along the line, smaller with the distance, and their sagging wires. */
function poles(rand) {
  const out = [];
  const tops = [];
  for (const t of [0.12, 0.33, 0.52, 0.7, 0.86]) {
    const b = bezier(MAIN, t);
    const h = 170 - t * 110;
    const [x, y] = [b.x, b.y - 26 + t * 12];
    const top = y - h;
    tops.push([x, top + 4]);
    out.push(
      pen(
        rand,
        lineD([
          [x, y],
          [x + 1, top],
        ]),
        1.2 + h / 130,
      ),
    );
    out.push(
      pen(
        rand,
        lineD([
          [x - h * 0.12, top + 6],
          [x + h * 0.12, top + 4],
        ]),
        1.1,
      ),
    );
  }
  for (let i = 0; i + 1 < tops.length; i++) {
    const [a, b] = [tops[i], tops[i + 1]];
    const mid = [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2 + 10];
    out.push(
      pen(rand, `M${f1(a[0])} ${f1(a[1])} Q${f1(mid[0])} ${f1(mid[1])} ${f1(b[0])} ${f1(b[1])}`, 0.8, {
        opacity: 0.55,
        twice: false,
      }),
    );
  }
  return out.join("\n");
}

