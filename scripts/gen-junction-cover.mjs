/** Short ink strokes of grass and a few tufts. */
function grass(rand, x0, x1, yOf, count) {
  const out = [];
  for (let i = 0; i < count; i++) {
    const x = x0 + rand() * (x1 - x0);
    const y = yOf(x) + rand() * 10;
    const h = 6 + rand() * 12;
    const lean = (rand() - 0.5) * 8;
    out.push(
      pen(rand, `M${f1(x)} ${f1(y)} q${f1(lean / 2)} ${f1(-h / 2)} ${f1(lean)} ${f1(-h)}`, 0.9, {
        opacity: 0.55,
        twice: false,
      }),
    );
  }
  return out.join("\n");
}

